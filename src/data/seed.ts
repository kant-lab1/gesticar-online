function docs(overrides?: Partial<VehicleDocument>[]): VehicleDocument[] {
  const base: VehicleDocument[] = [
    { id: uid('doc'), name: 'Permiso de circulación', status: 'correcto' },
    { id: uid('doc'), name: 'Ficha técnica', status: 'correcto' },
    { id: uid('doc'), name: 'Contrato de compra', status: 'correcto' },
    { id: uid('doc'), name: 'Factura', status: 'correcto' },
    { id: uid('doc'), name: 'ITV', status: 'correcto' },
    { id: uid('doc'), name: 'Informe DGT', status: 'correcto' },
    { id: uid('doc'), name: 'Garantía', status: 'correcto' },
  ]
  if (!overrides) return base
  return base.map((d, i) => ({ ...d, ...(overrides[i] ?? {}) }))
}

function exps(
  vehicleId: string,
  items: Array<[string, VehicleExpense['category'], number, string]>,
): VehicleExpense[] {
  return items.map(([concept, category, amount, date], i) => ({
    id: `${vehicleId}_e${i + 1}`,
    vehicleId,
    concept,
    category,
    amount,
    date,
    supplier: category === 'Taller' ? 'Taller Atlántico' : 'Gestoria Sur',
  }))
}

const pub = (
  web: boolean,
  extras: Partial<Vehicle['publication']> = {},
): Vehicle['publication'] => ({
  web,
  autoscout24: web,
  cochesNet: web,
  wallapop: false,
  facebook: false,
  lastSyncAt: web ? '2026-08-11T10:32:00.000Z' : undefined,
  showPrice: true,
  showFinance: true,
  showPlate: false,
  autoPublish: web,
  ...extras,
})

type Draft = Omit<Vehicle, 'expenses' | 'documents' | 'publication' | 'photos' | 'description' | 'doors' | 'location'> & {
  expenses: VehicleExpense[]
  web?: boolean
  documents?: VehicleDocument[]
  description?: string
}

function v(d: Draft): Vehicle {
  return {
    doors: 5,
    location: 'Exposición Santa Cruz',
    photos: [],
    description:
      d.description ??
      `${d.brand} ${d.model} ${d.version} en excelente estado. Historial completo, listo para entrega.`,
    documents: d.documents ?? docs(),
    publication: pub(d.web ?? d.status === 'disponible', {
      webSlug: `${d.brand}-${d.model}-${d.version}`.toLowerCase().replace(/\s+/g, '-'),
      title: `${d.brand} ${d.model} ${d.version}`,
      description: `${d.brand} ${d.model} ${d.year} · ${d.km.toLocaleString('es-ES')} km · ${d.fuel} · ${d.gearbox}`,
    }),
    ...d,
  }
}

